CREATE TABLE Endereco (
    ID_Endereco NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Rua         VARCHAR2(100) NOT NULL,
    Numero      VARCHAR2(6)   NOT NULL,
    Bairro      VARCHAR2(70)  NOT NULL,
    Cidade      VARCHAR2(100) NOT NULL,
    Estado      CHAR(2)       NOT NULL CHECK (Estado IN (
                    'AC', 'AL', 'AP', 'AM', 'BA', 'CE', 'DF', 'ES', 'GO',
                    'MA', 'MT', 'MS', 'MG', 'PA', 'PB', 'PR', 'PE', 'PI',
                    'RJ', 'RN', 'RS', 'RO', 'RR', 'SC', 'SP', 'SE', 'TO')),
    CEP         CHAR(8)       NOT NULL CHECK (REGEXP_LIKE(CEP, '^[0-9]{8}$')),
    Complemento VARCHAR2(60),
    UNIQUE (CEP, Rua, Numero, Complemento)
);

CREATE TABLE Especie (
    ID_Especie NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Nome       VARCHAR2(50) NOT NULL UNIQUE
);

CREATE TABLE Raca (
    ID_Raca    NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_Especie NUMBER(10)   NOT NULL REFERENCES Especie (ID_Especie),
    Nome       VARCHAR2(30) NOT NULL,
    UNIQUE (ID_Especie, Nome)
);

CREATE TABLE Unidade_ONG (
    ID_Unidade_ONG     NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_Endereco        NUMBER(10)   NOT NULL REFERENCES Endereco (ID_Endereco),
    Capacidade         NUMBER(5)    NOT NULL,
    Limite_Voluntarios NUMBER(5)    NOT NULL,
    Nome_Unidade       VARCHAR2(50) NOT NULL
);

CREATE TABLE Pessoa (
    ID_Pessoa       NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_Endereco     NUMBER(10)    NOT NULL REFERENCES Endereco (ID_Endereco),
    Estado_Civil    VARCHAR2(15)  CHECK (Estado_Civil IN (
                        'SOLTEIRO', 'CASADO', 'UNIAO_ESTAVEL',
                        'VIUVO', 'DIVORCIADO')),
    CPF             CHAR(11)      NOT NULL UNIQUE
                        CHECK (REGEXP_LIKE(CPF, '^[0-9]{11}$')),
    Nome            VARCHAR2(200) NOT NULL,
    Data_Nascimento DATE          NOT NULL,
    Telefone        VARCHAR2(18)  NOT NULL,
    Email           VARCHAR2(120)
);

CREATE TABLE Animal (
    ID_Animal                  NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_Unidade_ONG             NUMBER(10)   NOT NULL REFERENCES Unidade_ONG (ID_Unidade_ONG),
    ID_Raca                    NUMBER(10)   NOT NULL REFERENCES Raca (ID_Raca),
    Nome                       VARCHAR2(20),
    Data_Resgate               DATE         NOT NULL,
    Data_Nascimento_Estipulada DATE         NOT NULL,
    Sexo                       CHAR(1)      NOT NULL CHECK (Sexo IN ('F', 'M', 'I')),
    Status                     VARCHAR2(20) NOT NULL CHECK (Status IN (
                                   'EM_TRATAMENTO', 'DISPONIVEL', 'EM_PROCESSO',
                                   'ADOTADO', 'OBITO')),
    CHECK (Data_Resgate >= Data_Nascimento_Estipulada)
);

CREATE TABLE Despesa (
    ID_Despesa     NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_Unidade_ONG NUMBER(10)   NOT NULL REFERENCES Unidade_ONG (ID_Unidade_ONG),
    Tipo           VARCHAR2(20) NOT NULL,
    Valor          NUMBER(10,2) NOT NULL CHECK (Valor > 0),
    Data_Despesa   DATE         NOT NULL
);

CREATE TABLE Voluntariado (
    ID_Voluntariado NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_Unidade_ONG  NUMBER(10)   NOT NULL REFERENCES Unidade_ONG (ID_Unidade_ONG),
    ID_Pessoa       NUMBER(10)   NOT NULL REFERENCES Pessoa (ID_Pessoa),
    Funcao          VARCHAR2(15) NOT NULL CHECK (Funcao IN (
                        'CUIDADOR', 'PASSEADOR', 'RESGATE', 'TRANSPORTE',
                        'LIMPEZA', 'ADMINISTRATIVO', 'EVENTOS')),
    Data_Inicio     DATE         NOT NULL,
    Data_Fim        DATE,
    CHECK (Data_Fim >= Data_Inicio)
);

CREATE TABLE Doacao (
    ID_Doacao      NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_Pessoa      NUMBER(10)   NOT NULL REFERENCES Pessoa (ID_Pessoa),
    ID_Unidade_ONG NUMBER(10)   NOT NULL REFERENCES Unidade_ONG (ID_Unidade_ONG),
    Valor          NUMBER(10,2) NOT NULL CHECK (Valor > 0),
    Data_Doacao    DATE         NOT NULL,
    Metodo         VARCHAR2(20) NOT NULL CHECK (Metodo IN (
                       'PIX', 'DINHEIRO', 'CARTAO_CREDITO',
                       'CARTAO_DEBITO', 'TRANSFERENCIA', 'BOLETO'))
);

CREATE TABLE Mandato_Diretoria (
    ID_Mandato_Diretoria NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_Unidade_ONG       NUMBER(10)   NOT NULL REFERENCES Unidade_ONG (ID_Unidade_ONG),
    ID_Pessoa            NUMBER(10)   NOT NULL REFERENCES Pessoa (ID_Pessoa),
    Funcao               VARCHAR2(20) NOT NULL CHECK (Funcao IN (
                             'PRESIDENTE', 'VICE_PRESIDENTE',
                             'SECRETARIO', 'TESOUREIRO')),
    Remuneracao          NUMBER(10,2) NOT NULL CHECK (Remuneracao >= 0),
    Data_Inicio          DATE         NOT NULL,
    Data_Saida           DATE,
    CHECK (Data_Saida >= Data_Inicio)
);

CREATE TABLE Adocao (
    ID_Adocao      NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_Pessoa      NUMBER(10)   NOT NULL REFERENCES Pessoa (ID_Pessoa),
    ID_Animal      NUMBER(10)   NOT NULL REFERENCES Animal (ID_Animal),
    Data_Inicio    DATE         NOT NULL,
    Data_Conclusao DATE,
    Status         VARCHAR2(15) NOT NULL CHECK (Status IN (
                       'EM_ANALISE', 'APROVADA', 'REPROVADA',
                       'CANCELADA', 'CONCLUIDA', 'DEVOLVIDA')),
    CHECK (Data_Conclusao >= Data_Inicio)
);

CREATE TABLE Vacinacao (
    ID_Vacinacao   NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_Animal      NUMBER(10)   NOT NULL REFERENCES Animal (ID_Animal),
    Vacina         VARCHAR2(30) NOT NULL,
    Dose           NUMBER(2)    NOT NULL CHECK (Dose > 0),
    Data_Aplicacao DATE         NOT NULL,
    UNIQUE (ID_Animal, Vacina, Dose)
);

CREATE TABLE Historico_Veterinario (
    ID_Historico_Veterinario NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_Animal                NUMBER(10)    NOT NULL REFERENCES Animal (ID_Animal),
    Queixa                   VARCHAR2(300) NOT NULL,
    Estado_Tratamento        VARCHAR2(20)  NOT NULL CHECK (Estado_Tratamento IN (
                                 'AGUARDANDO', 'SEM_TRATAMENTO', 'EM_ANDAMENTO',
                                 'CONCLUIDO', 'INTERROMPIDO')),
    Diagnostico              VARCHAR2(60),
    Data_Atendimento         DATE          NOT NULL,
    Tratamento               VARCHAR2(300)
);

CREATE TABLE Historico_Status (
    ID_Historico_Status NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_Animal           NUMBER(10)   NOT NULL REFERENCES Animal (ID_Animal),
    Status_Anterior     VARCHAR2(20) CHECK (Status_Anterior IN (
                            'EM_TRATAMENTO', 'DISPONIVEL', 'EM_PROCESSO',
                            'ADOTADO', 'OBITO')),
    Status_Novo         VARCHAR2(20) NOT NULL CHECK (Status_Novo IN (
                            'EM_TRATAMENTO', 'DISPONIVEL', 'EM_PROCESSO',
                            'ADOTADO', 'OBITO')),
    Data_Alteracao      DATE         DEFAULT SYSDATE NOT NULL,
    CHECK (Status_Anterior <> Status_Novo)
);

CREATE UNIQUE INDEX uq_adocao_ativa ON Adocao (
    CASE WHEN Status IN ('EM_ANALISE', 'APROVADA', 'CONCLUIDA')
         THEN ID_Animal END
);

CREATE UNIQUE INDEX uq_voluntariado_ativo ON Voluntariado (
    CASE WHEN Data_Fim IS NULL THEN ID_Pessoa END,
    CASE WHEN Data_Fim IS NULL THEN ID_Unidade_ONG END
);

CREATE UNIQUE INDEX uq_mandato_ativo ON Mandato_Diretoria (
    CASE WHEN Data_Saida IS NULL THEN ID_Unidade_ONG END,
    CASE WHEN Data_Saida IS NULL THEN Funcao END
);